const buildingMap = new Map(campusBuildings.map(building => [building.id, building]));

export const campusRoutes: Route[] = campusRouteLinks.map(route => {
  const from = buildingMap.get(route.from_id);
  const to = buildingMap.get(route.to_id);
  if (!from || !to) {
    return {
      ...route,
      distance: 0,
      duration: 0,
    };
  }
  const distance = Math.round(
    Math.hypot(from.latitude - to.latitude, from.longitude - to.longitude) * 1000
  );
  const duration = Math.max(1, Math.round(distance / 80));
  return {
    ...route,
    distance,
    duration,
  };
});

